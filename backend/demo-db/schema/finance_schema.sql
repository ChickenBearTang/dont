-- Spring 본 DB 의 금융 테이블 (PostgreSQL). demo DB 용.
--
-- !! 출처 !!
--   저장소에는 이 DB 의 DDL 이 없다 (spring.jpa.hibernate.ddl-auto=none). 그래서 JPA 엔티티
--   (backend/src/main/java/.../auth/entity/User, community/entity/Cohort, fin/account/entity/*,
--   fin/card/entity/*, common/entity/BaseEntity)의 컬럼 이름·길이·NOT NULL 을 그대로 옮겼다.
--   운영 DB 의 실제 인덱스·제약·기본값은 확인하지 못했다. 실제 DDL 을 받으면 이 파일과 비교해야 한다.
--   (tests/test_demo_db.py 가 엔티티의 컬럼 목록과 이 파일이 만드는 컬럼 목록이 같은지 검사한다.)
--
-- 엔티티에 없는데 데모에서 더한 것 (운영에 있는지 모름):
--   * 일반 long 컬럼(accounts.user_id, savings_settings.*_id, card_transactions.user_id)의 FK
--   * 조회용 인덱스 (idx_demo_*)
--   JPA 가 @ManyToOne 으로 선언한 FK(users.cohort_id, cards.user_id, card_transactions.card_id,
--   account_transactions.account_id)는 엔티티 그대로다.

CREATE TABLE IF NOT EXISTS cohorts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_code   VARCHAR(50) NOT NULL UNIQUE,
    generation_no INTEGER     NOT NULL UNIQUE,
    start_date    DATE        NOT NULL,
    end_date      DATE        NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                      VARCHAR(255) NOT NULL UNIQUE,
    password                   VARCHAR(255) NOT NULL,
    name                       VARCHAR(50)  NOT NULL,
    birth_date                 DATE         NOT NULL,
    nickname                   VARCHAR(60),
    profile_image_url          VARCHAR(255),
    terms_agreed               BOOLEAN      NOT NULL,
    terms_agreed_at            TIMESTAMP(6),
    monthly_saving_goal_amount NUMERIC(15, 2),
    onboarding_status          VARCHAR(20),
    user_role                  VARCHAR(32)  NOT NULL,
    status                     VARCHAR(20)  NOT NULL,
    deleted_at                 TIMESTAMP(6),
    cohort_id                  BIGINT       NOT NULL REFERENCES cohorts (id),
    created_at                 TIMESTAMP(6) NOT NULL,
    updated_at                 TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS accounts (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT        NOT NULL REFERENCES users (id),
    account_no              VARCHAR(30)   NOT NULL UNIQUE,
    bank_code               VARCHAR(10)   NOT NULL,
    bank_name               VARCHAR(100)  NOT NULL,
    account_role            VARCHAR(20)   NOT NULL,  -- LINKED_DEPOSIT | SAVE_BOX
    is_primary              BOOLEAN       NOT NULL,
    account_type_code       VARCHAR(20),
    account_type_name       VARCHAR(100),
    account_name            VARCHAR(100),
    account_created_date    DATE,
    account_expiry_date     DATE,
    daily_transfer_limit    NUMERIC(15, 2),
    one_time_transfer_limit NUMERIC(15, 2),
    balance                 NUMERIC(15, 2) NOT NULL,
    last_transaction_date   DATE,
    currency_code           VARCHAR(10),
    status                  VARCHAR(20)   NOT NULL,  -- ACTIVE | INACTIVE | CLOSED | SUSPENDED
    user_name               VARCHAR(100),
    created_at              TIMESTAMP(6)  NOT NULL,
    updated_at              TIMESTAMP(6)  NOT NULL
);

-- BaseEntity 를 상속하지 않고 created_at 만 있다 (updated_at 없음).
CREATE TABLE IF NOT EXISTS account_transactions (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at             TIMESTAMP(6)   NOT NULL,
    account_id             BIGINT         NOT NULL REFERENCES accounts (id),
    transaction_unique_no  VARCHAR(30)    NOT NULL UNIQUE,
    transaction_date       DATE           NOT NULL,
    transaction_time       VARCHAR(10)    NOT NULL,
    transaction_type       VARCHAR(10)    NOT NULL,  -- "1" 입금, "2" 출금 (AccountService 가 "1" 로 자동저축 대상을 찾는다)
    transaction_type_name  VARCHAR(30),
    transaction_account_no VARCHAR(30),
    transaction_amount     NUMERIC(15, 2) NOT NULL,
    after_balance          NUMERIC(15, 2) NOT NULL,
    transaction_summary    VARCHAR(200),
    transaction_memo       VARCHAR(500),
    auto_savings_processed BOOLEAN        NOT NULL
);

CREATE TABLE IF NOT EXISTS savings_settings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT         NOT NULL REFERENCES users (id),
    primary_account_id BIGINT         NOT NULL REFERENCES accounts (id),
    savebox_account_id BIGINT         NOT NULL REFERENCES accounts (id),
    keyword            VARCHAR(100)   NOT NULL,
    savings_amount     NUMERIC(15, 2) NOT NULL,
    is_active          BOOLEAN        NOT NULL,
    created_at         TIMESTAMP(6)   NOT NULL,
    updated_at         TIMESTAMP(6)   NOT NULL
);

CREATE TABLE IF NOT EXISTS cards (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT       NOT NULL REFERENCES users (id),
    card_no               VARCHAR(64)  NOT NULL,
    cvc                   VARCHAR(8)   NOT NULL,
    card_unique_no        VARCHAR(128),
    card_issuer_code      VARCHAR(32),
    card_issuer_name      VARCHAR(128),
    card_name             VARCHAR(128),
    card_description      VARCHAR(255),
    baseline_performance  BIGINT,
    max_benefit_limit     BIGINT,
    card_expiry_date      VARCHAR(32),
    withdrawal_account_no VARCHAR(64),
    withdrawal_date       VARCHAR(32),   -- 보통 매달 결제일(일) 문자열 "1"~"28". FinanceProfileService 가 해석한다.
    created_at            TIMESTAMP(6) NOT NULL,
    updated_at            TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS card_transactions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id            BIGINT       NOT NULL REFERENCES cards (id),
    transaction_date   DATE         NOT NULL,
    transaction_time   VARCHAR(16),
    merchant_name      VARCHAR(255),
    category_name      VARCHAR(128),
    transaction_amount BIGINT,
    transaction_type   VARCHAR(64),
    approval_no        VARCHAR(64),
    description        VARCHAR(500),
    user_id            BIGINT       NOT NULL REFERENCES users (id),
    created_at         TIMESTAMP(6) NOT NULL,
    updated_at         TIMESTAMP(6) NOT NULL
);

-- 데모에서 더한 조회용 인덱스 (운영에 같은 것이 있는지는 모름)
CREATE INDEX IF NOT EXISTS idx_demo_accounts_user ON accounts (user_id);
CREATE INDEX IF NOT EXISTS idx_demo_account_tx_account_date ON account_transactions (account_id, transaction_date);
CREATE INDEX IF NOT EXISTS idx_demo_cards_user ON cards (user_id);
CREATE INDEX IF NOT EXISTS idx_demo_card_tx_user_date ON card_transactions (user_id, transaction_date);
